class MCP:
    """An MCP server: register tools with ``@mcp.tool``, then ``mcp.run()``."""

    def __init__(self, name: str, instructions: str = "", version: str = "1.0.0") -> None:
        self.name = name
        self.instructions = instructions
        self.version = version
        self.tools: dict[str, Tool] = {}
        self._out_lock = threading.Lock()

    # -- registration ---------------------------------------------------------
    def tool(self, fn: Callable[..., Any] | None = None, *, name: str | None = None, description: str | None = None, read_only: bool | None = None, destructive: bool | None = None) -> Any:
        """Decorator. ``@mcp.tool`` or ``@mcp.tool(name=..., read_only=True)``."""

        def deco(f: Callable[..., Any]) -> Callable[..., Any]:
            ann: dict[str, Any] = {}
            if read_only is not None:
                ann["readOnlyHint"] = read_only
            if destructive is not None:
                ann["destructiveHint"] = destructive
            t = Tool(f, name=name, description=description, annotations=ann)
            self.tools[t.name] = t
            return f

        return deco(fn) if fn is not None else deco

    # -- protocol -------------------------------------------------------------
    def handle(self, msg: Any) -> Any:
        """One JSON-RPC message (or batch) in, the reply (or None for notifications) out."""
        if isinstance(msg, list):
            replies = [r for r in (self.handle(m) for m in msg) if r is not None]
            return replies or None
        if not isinstance(msg, dict) or msg.get("jsonrpc") != "2.0" or "method" not in msg:
            if isinstance(msg, dict) and ("result" in msg or "error" in msg):
                return None  # a reply to something we never sent; ignore
            return _err(msg.get("id") if isinstance(msg, dict) else None, -32600, "invalid request")
        mid, method, params = msg.get("id"), msg["method"], msg.get("params") or {}
        is_note = "id" not in msg
        try:
            result = self._dispatch(method, params)
        except _RPCError as e:
            return None if is_note else _err(mid, e.code, e.message)
        except Exception as e:  # noqa: BLE001
            log("internal error:", traceback.format_exc())
            return None if is_note else _err(mid, -32603, f"internal error: {e}")
        if is_note:
            return None
        return {"jsonrpc": "2.0", "id": mid, "result": result}

    def _dispatch(self, method: str, params: dict) -> Any:
        if method == "initialize":
            asked = params.get("protocolVersion") or PROTOCOL_VERSIONS[0]
            version = asked if asked in PROTOCOL_VERSIONS else PROTOCOL_VERSIONS[0]
            out: dict[str, Any] = {
                "protocolVersion": version,
                "capabilities": {"tools": {"listChanged": False}, "logging": {}},
                "serverInfo": {"name": self.name, "version": self.version},
            }
            if self.instructions:
                out["instructions"] = self.instructions
            return out
        if method == "ping":
            return {}
        if method.startswith("notifications/"):
            return None
        if method == "tools/list":
            return {"tools": [t.spec() for t in self.tools.values()]}
        if method == "tools/call":
            return self.call_tool(params.get("name", ""), params.get("arguments") or {})
        if method in ("resources/list", "resources/templates/list"):
            return {"resources": []} if method == "resources/list" else {"resourceTemplates": []}
        if method == "prompts/list":
            return {"prompts": []}
        if method == "logging/setLevel":
            return {}
        raise _RPCError(-32601, f"method not found: {method}")

    def call_tool(self, name: str, arguments: dict) -> dict:
        t = self.tools.get(name)
        if t is None:
            raise _RPCError(-32602, f"unknown tool {name!r}; available: {', '.join(self.tools)}")
        try:
            return _to_content(t.call(arguments))
        except (ToolError, HTTPError, SessionExpired) as e:
            return {"content": [{"type": "text", "text": str(e)}], "isError": True}
        except Exception as e:  # noqa: BLE001  (tool bugs are reported to the model, not crashes)
            log(f"tool {name} failed:", traceback.format_exc())
            return {"content": [{"type": "text", "text": f"{type(e).__name__}: {e}"}], "isError": True}

    # -- transports -----------------------------------------------------------
    def run_stdio(self) -> None:
        """Newline-delimited JSON-RPC on stdin/stdout (the MCP stdio transport)."""
        log(f"{self.name}: {len(self.tools)} tools on stdio")
        inp = sys.stdin.buffer if hasattr(sys.stdin, "buffer") else sys.stdin
        for raw in inp:
            line = raw.decode("utf-8", "replace").strip() if isinstance(raw, bytes) else raw.strip()
            if not line:
                continue
            try:
                msg = json.loads(line)
            except ValueError:
                self._write(_err(None, -32700, "parse error"))
                continue
            reply = self.handle(msg)
            if reply is not None:
                self._write(reply)

    def _write(self, obj: Any) -> None:
        data = json.dumps(obj, ensure_ascii=False, separators=(",", ":"), default=str)
        with self._out_lock:
            sys.stdout.write(data + "\n")
            sys.stdout.flush()

    def run_http(self, port: int = 8811, host: str = "127.0.0.1", path: str = "/mcp") -> None:
        """Streamable HTTP transport (JSON responses). POST JSON-RPC to http://host:port/mcp."""
        server = self

        class H(http.server.BaseHTTPRequestHandler):
            protocol_version = "HTTP/1.1"

            def log_message(self, *a: Any) -> None:
                pass

            def _send(self, code: int, body: bytes = b"", ctype: str = "application/json", extra: dict | None = None) -> None:
                self.send_response(code)
                self.send_header("Content-Type", ctype)
                self.send_header("Content-Length", str(len(body)))
                for k, v in (extra or {}).items():
                    self.send_header(k, v)
                self.end_headers()
                if body:
                    self.wfile.write(body)

            def _origin_ok(self) -> bool:
                origin = self.headers.get("Origin")
                if not origin:
                    return True
                h = urllib.parse.urlparse(origin).hostname or ""
                return h in ("127.0.0.1", "localhost", "::1") or os.environ.get("REVAPI_MCP_ALLOW_ORIGIN") in ("*", origin)

            def do_POST(self) -> None:  # noqa: N802
                if urllib.parse.urlparse(self.path).path != path:
                    return self._send(404, b'{"error":"not found"}')
                if not self._origin_ok():
                    return self._send(403, b'{"error":"origin not allowed"}')
                n = int(self.headers.get("Content-Length") or 0)
                try:
                    msg = json.loads(self.rfile.read(n) or b"null")
                except ValueError:
                    return self._send(400, json.dumps(_err(None, -32700, "parse error")).encode())
                reply = server.handle(msg)
                extra = {}
                if isinstance(msg, dict) and msg.get("method") == "initialize":
                    extra["Mcp-Session-Id"] = secrets.token_hex(16)
                if reply is None:
                    return self._send(202, b"", extra=extra)
                self._send(200, json.dumps(reply, ensure_ascii=False, default=str).encode(), extra=extra)

            def do_GET(self) -> None:  # noqa: N802
                if urllib.parse.urlparse(self.path).path == path:
                    return self._send(405, b"", extra={"Allow": "POST, DELETE"})  # no server-initiated stream
                body = json.dumps({"name": server.name, "mcp": f"http://{host}:{port}{path}", "tools": list(server.tools)}).encode()
                self._send(200, body)

            def do_DELETE(self) -> None:  # noqa: N802
                self._send(200 if urllib.parse.urlparse(self.path).path == path else 404)

        httpd = http.server.ThreadingHTTPServer((host, port), H)
        httpd.daemon_threads = True
        log(f"{self.name}: {len(self.tools)} tools on http://{host}:{httpd.server_address[1]}{path}")
        try:
            httpd.serve_forever()
        except KeyboardInterrupt:
            pass
        finally:
            httpd.server_close()

    def run(self, argv: list[str] | None = None) -> None:
        """Command line: stdio by default; --http PORT, --list, --call NAME JSON."""
        args = list(sys.argv[1:] if argv is None else argv)
        if "--list" in args:
            for t in self.tools.values():
                print(json.dumps(t.spec(), ensure_ascii=False, indent=1))
            return
        if "--call" in args:
            i = args.index("--call")
            name = args[i + 1] if len(args) > i + 1 else ""
            raw = args[i + 2] if len(args) > i + 2 else "{}"
            try:
                res = self.call_tool(name, json.loads(raw))
            except _RPCError as e:
                print(e.message, file=sys.stderr)
                raise SystemExit(2) from None
            for c in res["content"]:
                print(c.get("text", c))
            raise SystemExit(1 if res.get("isError") else 0)
        if "--http" in args:
            i = args.index("--http")
            port = int(args[i + 1]) if len(args) > i + 1 and args[i + 1].isdigit() else 8811
            host = args[args.index("--host") + 1] if "--host" in args else "127.0.0.1"
            return self.run_http(port, host)
        self.run_stdio()


class _RPCError(Exception):
    def __init__(self, code: int, message: str) -> None:
        super().__init__(message)
        self.code, self.message = code, message


def _err(mid: Any, code: int, message: str) -> dict:
    return {"jsonrpc": "2.0", "id": mid, "error": {"code": code, "message": message}}


