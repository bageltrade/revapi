class HTTPError(Exception):
    def __init__(self, response: Response) -> None:
        self.response = response
        body = response.text[:400].strip()
        super().__init__(f"HTTP {response.status} from {response.method} {response.url}" + (f": {body}" if body else ""))


class SessionExpired(Exception):
    """The site answered with a Cloudflare/CAPTCHA check: the saved session needs renewing."""


class Response:
    def __init__(self, method: str, url: str, status: int, headers: dict[str, str], body: bytes) -> None:
        self.method, self.url, self.status, self.headers, self.content = method, url, status, headers, body

    @property
    def ok(self) -> bool:
        return 200 <= self.status < 400

    @property
    def text(self) -> str:
        m = re.search(r"charset=([\w-]+)", self.headers.get("content-type", ""))
        try:
            return self.content.decode(m.group(1) if m else "utf-8", "replace")
        except LookupError:
            return self.content.decode("utf-8", "replace")

    def json(self) -> Any:
        try:
            return json.loads(self.text)
        except ValueError:
            raise ToolError(f"expected JSON from {self.url} but got {self.headers.get('content-type', 'unknown content')}: {self.text[:200]}") from None

    def raise_for_status(self) -> Response:
        if not self.ok:
            raise HTTPError(self)
        return self

    def __repr__(self) -> str:
        return f"<Response {self.status} {self.method} {self.url}>"


def _revapi_home() -> Path:
    return Path(os.environ.get("REVAPI_HOME", Path.home() / ".revapi"))


def _looks_like_check(status: int, headers: dict[str, str], body: bytes) -> bool:
    if headers.get("cf-mitigated", "").lower() == "challenge":
        return True
    if status in (403, 429, 503):
        head = body[:6000].decode("utf-8", "replace").lower()
        return "<title>just a moment" in head or "challenges.cloudflare.com" in head or "cf-chl" in head or "_cf_chl_opt" in head
    return False


class Session:
    """A small requests-like HTTP session on urllib (cookies, default headers, retries).

    If revapi saved a session for this host (``~/.revapi/sessions/<host>.json``, written after
    you pass a Cloudflare/CAPTCHA check in revapi's live view), its cookies and exact user agent
    are loaded automatically. When the site shows a check again, tools raise SessionExpired with
    the command that renews it.
    """

    def __init__(
        self, base_url: str = "", headers: dict[str, str] | None = None, cookies: dict[str, str] | str | None = None, timeout: float = 30, retries: int = 3, use_saved_session: bool = True
    ) -> None:
        self.base_url = base_url.rstrip("/")
        self.timeout = timeout
        self.retries = retries
        self.headers: dict[str, str] = {
            "User-Agent": "Mozilla/5.0 (Linux; Android 14) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Mobile Safari/537.36",
            "Accept": "application/json, text/plain, */*",
            "Accept-Language": "en-US,en;q=0.9",
            "Accept-Encoding": "gzip, deflate",
        }
        self.host = (urllib.parse.urlparse(self.base_url).hostname or "").lower()
        self.saved_session: dict | None = None
        if use_saved_session and self.host:
            self._load_saved()
        self.headers.update(headers or {})
        self.jar = http.cookiejar.CookieJar()
        self._opener = urllib.request.build_opener(urllib.request.HTTPCookieProcessor(self.jar))
        if self.saved_session:
            for c in self.saved_session.get("cookies", []):
                self.set_cookie(c.get("name", ""), c.get("value", ""), c.get("domain") or self.host, c.get("path") or "/")
        if isinstance(cookies, str):
            cookies = dict(p.strip().split("=", 1) for p in cookies.split(";") if "=" in p)
        for k, v in (cookies or {}).items():
            self.set_cookie(k, v)

    def _load_saved(self) -> None:
        p = _revapi_home() / "sessions" / f"{self.host}.json"
        try:
            self.saved_session = json.loads(p.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return
        if self.saved_session.get("user_agent"):
            self.headers["User-Agent"] = self.saved_session["user_agent"]
        log(f"using the saved session for {self.host} from {self.saved_session.get('saved_at', '?')}")

    def set_cookie(self, name: str, value: str, domain: str | None = None, path: str = "/") -> None:
        if not name:
            return
        dom = domain or self.host
        self.jar.set_cookie(http.cookiejar.Cookie(0, name, value, None, False, dom, True, dom.startswith("."), path, True, False, None, False, None, None, {}))

    @property
    def cookies(self) -> dict[str, str]:
        return {c.name: c.value or "" for c in self.jar}

    def url(self, path: str) -> str:
        if path.startswith(("http://", "https://")):
            return path
        return self.base_url + ("" if path.startswith("/") else "/") + path

    def request(
        self,
        method: str,
        path: str,
        *,
        params: dict | None = None,
        json_body: Any = None,
        data: Any = None,
        headers: dict[str, str] | None = None,
        timeout: float | None = None,
        allow_errors: bool = False,
        **kw: Any,
    ) -> Response:
        """Send a request. ``json=`` is accepted as an alias of ``json_body``. Raises HTTPError for 4xx/5xx
        unless ``allow_errors=True``; raises SessionExpired when the site shows a Cloudflare/CAPTCHA check."""
        if "json" in kw:
            json_body = kw.pop("json")
        if kw:
            raise TypeError(f"unexpected arguments: {', '.join(kw)}")
        url = self.url(path)
        if params:
            clean = {k: ("true" if v is True else "false" if v is False else v) for k, v in params.items() if v is not None}
            url += ("&" if "?" in url else "?") + urllib.parse.urlencode(clean, doseq=True)
        hdrs = {**self.headers, **(headers or {})}
        body: bytes | None = None
        if json_body is not None:
            body = json.dumps(json_body, ensure_ascii=False).encode()
            hdrs.setdefault("Content-Type", "application/json")
        elif isinstance(data, dict):
            body = urllib.parse.urlencode(data, doseq=True).encode()
            hdrs.setdefault("Content-Type", "application/x-www-form-urlencoded")
        elif isinstance(data, str):
            body = data.encode()
        elif isinstance(data, (bytes, bytearray)):
            body = bytes(data)
        attempt = 0
        while True:
            attempt += 1
            req = urllib.request.Request(url, data=body, headers=hdrs, method=method.upper())
            try:
                with self._opener.open(req, timeout=timeout or self.timeout) as r:
                    status, rh, raw = r.status, {k.lower(): v for k, v in r.headers.items()}, r.read()
            except urllib.error.HTTPError as e:
                status, rh, raw = e.code, {k.lower(): v for k, v in (e.headers or {}).items()}, e.read() or b""
            except (urllib.error.URLError, TimeoutError, ConnectionError, OSError) as e:
                if attempt <= self.retries:
                    time.sleep(min(8, 0.6 * 2**attempt))
                    continue
                raise ToolError(f"could not reach {url}: {getattr(e, 'reason', e)}") from None
            raw = _decode(raw, rh.get("content-encoding", ""))
            resp = Response(method.upper(), url, status, rh, raw)
            if _looks_like_check(status, rh, raw):
                site = f"{urllib.parse.urlparse(url).scheme}://{urllib.parse.urlparse(url).netloc}"
                raise SessionExpired(f"{urllib.parse.urlparse(url).hostname} is showing a Cloudflare/CAPTCHA check: the session expired. Run  revapi refresh {site}  then try again.")
            if status in (429, 500, 502, 503, 504) and attempt <= self.retries:
                wait = rh.get("retry-after", "")
                time.sleep(min(20, float(wait)) if wait.replace(".", "", 1).isdigit() else min(8, 0.6 * 2**attempt))
                continue
            if not allow_errors and status >= 400:
                raise HTTPError(resp)
            return resp

    def get(self, path: str, **kw: Any) -> Response:
        return self.request("GET", path, **kw)

    def post(self, path: str, **kw: Any) -> Response:
        return self.request("POST", path, **kw)

    def put(self, path: str, **kw: Any) -> Response:
        return self.request("PUT", path, **kw)

    def patch(self, path: str, **kw: Any) -> Response:
        return self.request("PATCH", path, **kw)

    def delete(self, path: str, **kw: Any) -> Response:
        return self.request("DELETE", path, **kw)


def _decode(raw: bytes, encoding: str) -> bytes:
    enc = encoding.lower()
    try:
        if "gzip" in enc:
            return gzip.decompress(raw)
        if "deflate" in enc:
            try:
                return zlib.decompress(raw)
            except zlib.error:
                return zlib.decompress(raw, -zlib.MAX_WBITS)
    except (OSError, zlib.error, EOFError):
        pass
    return raw
