# ============================================================================ schema from type hints

_DOC_ARG = re.compile(r"^\s{0,12}(\*{0,2}\w+)\s*(?:\(([^)]*)\))?\s*:\s*(.*)$")


def _parse_doc(doc: str) -> tuple[str, dict[str, str]]:
    """Description (text before Args:) and per-argument descriptions (Google or :param style)."""
    doc = inspect.cleandoc(doc or "")
    desc_lines: list[str] = []
    args: dict[str, str] = {}
    section, current = "desc", ""
    for line in doc.splitlines():
        s = line.strip()
        low = s.lower().rstrip(":")
        if low in ("args", "arguments", "parameters", "params"):
            section = "args"
            continue
        if low in ("returns", "return", "raises", "yields", "examples", "example", "notes"):
            section = "other"
            continue
        m = re.match(r":param\s+(\w+)\s*:\s*(.*)", s)
        if m:
            args[m.group(1)] = m.group(2)
            current = m.group(1)
            continue
        if section == "args":
            m = _DOC_ARG.match(line)
            if m and not line.startswith(" " * 12):
                current = m.group(1).lstrip("*")
                args[current] = m.group(3).strip()
            elif current and s:
                args[current] = (args[current] + " " + s).strip()
        elif section == "desc":
            desc_lines.append(line)
    return "\n".join(desc_lines).strip(), args


def _schema(tp: Any) -> dict:
    """JSON Schema for a Python type annotation."""
    if tp is inspect.Parameter.empty or tp is Any or tp is None:
        return {}
    origin = typing.get_origin(tp)
    args = typing.get_args(tp)
    if origin is typing.Union or (hasattr(types, "UnionType") and isinstance(tp, types.UnionType)):
        non_none = [a for a in args if a is not type(None)]
        if len(non_none) == 1:
            return _schema(non_none[0])
        return {"anyOf": [_schema(a) for a in non_none]}
    if origin is typing.Literal:
        vals = list(args)
        kinds = {type(v) for v in vals}
        out: dict[str, Any] = {"enum": vals}
        if kinds == {str}:
            out["type"] = "string"
        elif kinds <= {int}:
            out["type"] = "integer"
        return out
    if origin in (list, tuple, set, frozenset) or tp in (list, tuple, set):
        item = _schema(args[0]) if args else {}
        return {"type": "array", "items": item} if item else {"type": "array"}
    if origin is dict or tp is dict:
        out = {"type": "object"}
        if len(args) == 2 and _schema(args[1]):
            out["additionalProperties"] = _schema(args[1])
        return out
    if isinstance(tp, type) and issubclass(tp, enum.Enum):
        return {"enum": [m.value for m in tp]}
    if typing.is_typeddict(tp) if hasattr(typing, "is_typeddict") else False:
        hints = typing.get_type_hints(tp)
        req = getattr(tp, "__required_keys__", set(hints))
        return {"type": "object", "properties": {k: _schema(v) for k, v in hints.items()}, "required": sorted(req)}
    return {
        str: {"type": "string"},
        int: {"type": "integer"},
        float: {"type": "number"},
        bool: {"type": "boolean"},
        bytes: {"type": "string"},
    }.get(tp, {})


def _resolve_hint(hint: Any, fn: Callable[..., Any]) -> Any:
    """A string annotation evaluated with typing's names available (Literal, Optional, ...)."""
    if not isinstance(hint, str):
        return hint
    ns: dict[str, Any] = {k: getattr(typing, k) for k in ("Any", "Literal", "Optional", "Union", "List", "Dict", "Tuple", "Set")}
    ns.update(getattr(fn, "__globals__", {}))
    try:
        return eval(hint, ns)  # noqa: S307  (the server's own annotation text)
    except Exception:  # noqa: BLE001
        return {"str": str, "int": int, "float": float, "bool": bool, "dict": dict, "list": list}.get(hint.split("|")[0].strip(), inspect.Parameter.empty)


def _coerce(value: Any, tp: Any) -> Any:
    """Gently fix common client mistakes ("5" for an int, "true" for a bool, a JSON string for a list)."""
    if value is None or tp in (inspect.Parameter.empty, Any):
        return value
    origin = typing.get_origin(tp)
    if origin is typing.Union or (hasattr(types, "UnionType") and isinstance(tp, types.UnionType)):
        non_none = [a for a in typing.get_args(tp) if a is not type(None)]
        return _coerce(value, non_none[0]) if len(non_none) == 1 else value
    try:
        if tp is int and isinstance(value, str) and re.fullmatch(r"-?\d+", value.strip()):
            return int(value)
        if tp is int and isinstance(value, float) and value.is_integer():
            return int(value)
        if tp is float and isinstance(value, (str, int)) and not isinstance(value, bool):
            return float(value)
        if tp is bool and isinstance(value, str) and value.lower() in ("true", "false", "1", "0", "yes", "no"):
            return value.lower() in ("true", "1", "yes")
        if tp is str and isinstance(value, (int, float)) and not isinstance(value, bool):
            return str(value)
        if (origin in (list, dict) or tp in (list, dict)) and isinstance(value, str) and value.strip()[:1] in "[{":
            return json.loads(value)
    except (ValueError, TypeError):
        pass
    return value


class Tool:
    def __init__(self, fn: Callable[..., Any], name: str | None = None, description: str | None = None, annotations: dict | None = None) -> None:
        self.fn = fn
        self.name = name or fn.__name__
        desc, arg_docs = _parse_doc(fn.__doc__ or "")
        self.description = description or desc or self.name.replace("_", " ")
        self.annotations = annotations or {}
        try:
            hints = typing.get_type_hints(fn)
        except Exception:  # noqa: BLE001  (a name not importable at module level: resolve one by one)
            hints = {k: _resolve_hint(v, fn) for k, v in getattr(fn, "__annotations__", {}).items()}
        self.hints = hints
        self.params = [p for p in inspect.signature(fn).parameters.values() if p.kind in (p.POSITIONAL_OR_KEYWORD, p.KEYWORD_ONLY)]
        props: dict[str, Any] = {}
        required: list[str] = []
        for p in self.params:
            sch = dict(_schema(hints.get(p.name, p.annotation)))
            if p.name in arg_docs:
                sch["description"] = arg_docs[p.name]
            if p.default is inspect.Parameter.empty:
                required.append(p.name)
            elif p.default is not None and isinstance(p.default, (str, int, float, bool, list, dict)):
                sch["default"] = p.default
            props[p.name] = sch
        self.input_schema = {"type": "object", "properties": props, "required": required, "additionalProperties": False}

    def spec(self) -> dict:
        out = {"name": self.name, "description": self.description, "inputSchema": self.input_schema}
        if self.annotations:
            out["annotations"] = self.annotations
        return out

    def call(self, arguments: dict | None) -> Any:
        arguments = dict(arguments or {})
        known = {p.name for p in self.params}
        unknown = sorted(set(arguments) - known)
        if unknown:
            raise ToolError(f"unknown argument(s) {', '.join(unknown)}; expected: {', '.join(sorted(known)) or 'none'}")
        missing = [p.name for p in self.params if p.default is inspect.Parameter.empty and p.name not in arguments]
        if missing:
            raise ToolError(f"missing required argument(s): {', '.join(missing)}")
        kwargs = {k: _coerce(v, self.hints.get(k, inspect.Parameter.empty)) for k, v in arguments.items()}
        return self.fn(**kwargs)


def _to_content(result: Any) -> dict:
    """MCP CallToolResult for whatever a tool returned."""
    if isinstance(result, dict) and isinstance(result.get("content"), list) and all(isinstance(c, dict) and "type" in c for c in result["content"]):
        return result  # already a CallToolResult
    if isinstance(result, Response):
        result = result.json() if "json" in result.headers.get("content-type", "") else result.text
    if isinstance(result, (bytes, bytearray)):
        result = result.decode("utf-8", "replace")
    if isinstance(result, str):
        return {"content": [{"type": "text", "text": result}], "isError": False}
    text = json.dumps(result, ensure_ascii=False, indent=1, default=str)
    out: dict[str, Any] = {"content": [{"type": "text", "text": text}], "isError": False}
    if isinstance(result, dict):
        out["structuredContent"] = json.loads(json.dumps(result, default=str))
    return out


